# 不统一到新字体的保留字(数据中两种写法并存,统一会造成语义错误)
_KEEP_KYU = {'築', '機'}

_KANJI_RE = re.compile(r'[\u3400-\u9fff\uf900-\ufaff]')


def canonical_kanji(s):
    """汉字canonical:NFKC -> s2t(简->繁/旧) -> JP_MAP(->新字体);々重复前字;ケ/ヵ->ヶ(夹在汉字间)"""
    s = unicodedata.normalize('NFKC', s or '')
    out = []
    prev = ''
    for ch in s:
        if ch in '々':
            if prev and _KANJI_RE.match(prev):
                out.append(prev)
            else:
                out.append(ch)
            continue
        if ch in _KEEP_KYU:
            out.append(ch)
            prev = ch
            continue
        k = _s2t.convert(ch) if _KANJI_RE.match(ch) else ch
        out.append(JP_MAP.get(k, k))
        prev = ch
    res = ''.join(out)
    # ケ/ヵ 夹在汉字间 -> ヶ
    res = re.sub(r'(?<=[\u3400-\u9fff])[ケヵ](?=[\u3400-\u9fff])', 'ヶ', res)
    return res


