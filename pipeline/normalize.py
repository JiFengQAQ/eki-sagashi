def norm_kana(s):
    """假名归一:NFKC -> 片假名转平假名 -> 长音符号ー按前行展开(オ段->う)"""
    s = unicodedata.normalize('NFKC', s or '')
    s = ''.join(_KATA2HIRA.get(c, c) for c in s)
    out = []
    for c in s:
        if c == 'ー' and out:
            prev = out[-1]
            if prev in _VOWEL_AFTER:
                out.append(_VOWEL_AFTER[prev])
                continue
        out.append(c)
    return ''.join(out)


_MACRON = str.maketrans({'ā': 'a', 'ē': 'e', 'ī': 'i', 'ō': 'o', 'ū': 'u',
                         'Ā': 'a', 'Ē': 'e', 'Ī': 'i', 'Ō': 'o', 'Ū': 'u'})


def norm_roma(s):
    """罗马音归一:小写 -> 去长音符号 -> 去空格/连字符"""
    s = unicodedata.normalize('NFKC', s or '').lower()
    s = s.translate(_MACRON)
    s = re.sub(r'[\s\'\-]', '', s)
    return s


def norm_roma_hepburn(s):
    """标准Hepburn无长音表记: oo/ou -> o, uu -> u (大阪->osaka, 京都->kyoto, 東京->tokyo)
    日语罗马音中 oo/ou/uu 均为长音(おう/おお/うう), 缩写安全"""
    s = norm_roma(s)
    s = s.replace('ou', 'o').replace('oo', 'o').replace('uu', 'u')
    return s


def roma_variants(s):
    """罗马音索引变体:无长音形 + 长音转ou形(东京->tokyo/toukyou)"""
    base = norm_roma(s)
    # 正确做法:在去长音前,把ō替换为ou
    low = unicodedata.normalize('NFKC', s or '').lower()
    ou_form = low
    for mac, plain in [('ō', 'ou'), ('ū', 'uu'), ('ā', 'aa'), ('ē', 'ee'), ('ī', 'ii'),
                       ('Ō', 'ou'), ('Ū', 'uu'), ('Ā', 'aa'), ('Ē', 'ee'), ('Ī', 'ii')]:
        ou_form = ou_form.replace(mac, plain)
    ou_form = re.sub(r'[\s\'\-]', '', ou_form)
    return list(dict.fromkeys([base, ou_form]))


def norm_station_name(s):
    """站名归一:NFKC -> 去括号内容 -> 去尾駅 -> 去空白/中黑点"""
    s = unicodedata.normalize('NFKC', s or '')
    s = re.sub(r'[（(].*?[)）]', '', s)
    s = re.sub(r'駅$', '', s)
    s = re.sub(r'[\s　・･]', '', s)
    return s


